"""Writes src/docfx/toc.yml from the README files git tracks.

Each application folder (RetroX25.*) and the demo folder keep a README.md. DocFX publishes them
as articles under apps/ (see the third content group in docfx.json). The header menu lists
Home, Applications, API Reference and a link to the GitHub repository, so a reader on any page
is one click from the source.

Run from anywhere:   python src/docfx/gen_toc.py
Check only (CI):     python src/docfx/gen_toc.py --check
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
TOC = os.path.join(HERE, "toc.yml")
REPO_URL = "https://github.com/RetroCoreLabs/RetroX25"


def first_heading(path):
    """Returns the first Markdown heading of a file, without the hash marks."""
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            if line.startswith("# "):
                return line[2:].strip()
    return os.path.basename(os.path.dirname(path))


def tracked_readmes():
    """Lists the tracked README.md files that become articles, in a stable order."""
    out = subprocess.run(
        ["git", "ls-files", "--", "RetroX25.*/README.md", "demo/README.md"],
        cwd=SRC, check=True, capture_output=True, text=True).stdout
    return sorted(line for line in out.splitlines() if line)


def build():
    lines = [
        "# generated by src/docfx/gen_toc.py; edit the README files and run it again",
        "- name: Home",
        "  href: index.md",
        "- name: Applications",
        "  items:",
    ]
    for rel in tracked_readmes():
        name = first_heading(os.path.join(SRC, rel)).replace('"', "'")
        lines.append('  - name: "%s"' % name)
        # DocFX resolves a toc link against the SOURCE path of the article, which is one level
        # above this folder; the "apps" destination only shows up in the built site.
        lines.append("    href: ../%s" % rel)
    lines += [
        "- name: API Reference",
        "  href: api/",
        "  topicHref: api/index.md",
        "- name: GitHub",
        "  href: %s" % REPO_URL,
        "",
    ]
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv:
        with open(TOC, encoding="utf-8", newline="") as handle:
            current = handle.read().replace("\r\n", "\n")
        if current != text:
            print("toc.yml is out of date; run python src/docfx/gen_toc.py", file=sys.stderr)
            return 1
        return 0
    with open(TOC, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
